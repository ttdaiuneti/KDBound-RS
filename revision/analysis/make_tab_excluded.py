"""R1.13: table of the two tables dropped at screening (eeg-eye-state, numerai28-6) from
code/excluded/excluded_run.jsonl -> manuscript/tab_excluded.tex, plus the check numbers used in the text.
Duplicate records (the grid was started twice; the second process re-ran units it had not yet seen as done) are
dropped: the first record of each (dataset, criterion, param, fold, method) is kept."""
import json, os, statistics as st
HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, "..", "code", "excluded", "excluded_run.jsonl")
OUT = os.path.join(HERE, "..", "manuscript", "tab_excluded.tex")
recs = {}
for ln in open(SRC):
    r = json.loads(ln); recs.setdefault((r["dataset"], r["criterion"], r["param"], r["fold"], r["method"]), r)

EXIST = {"NRS": ("FNC", "HASH"), "FRS": ("FA-FPR",)}
NAME = {"eeg-eye-state": "eeg-eye-state", "numerai28-6": "numerai28.6"}


def cell(ds, c, p, m):
    rs = [r for k, r in recs.items() if k[:3] == (ds, c, p) and k[4] == m]
    ok = [r["time"] for r in rs if r["status"] == "ok"]
    if len(ok) == 5:
        return st.mean(ok)
    return None                                   # timeout on fold 1


def f(t):
    return "T" if t is None else (f"{t:.2f}" if t < 10 else f"{t:.1f}")


rows, agree_all, n_cmp = [], True, 0
for ds in ("eeg-eye-state", "numerai28-6"):
    for c, ps in (("NRS", ("0.05", "0.10", "0.15", "0.20")), ("FRS", ("0.25", "std"))):
        for p in ps:
            for fo in range(1, 6):
                Rs = {tuple(r["R"]) for k, r in recs.items() if k[:4] == (ds, c, p, fo) and r["status"] == "ok"}
                n_cmp += 1; agree_all &= len(Rs) == 1
            sz = [len(r["R"]) for k, r in recs.items() if k[:3] == (ds, c, p) and k[4] == "KD-PA+B3"]
            ours, kd = cell(ds, c, p, "KD-PA+B3"), cell(ds, c, p, "KD-PA")
            ex = {m: cell(ds, c, p, m) for m in EXIST[c]}
            fin = {m: t for m, t in ex.items() if t is not None}
            if fin:
                bm = min(fin, key=fin.get); best = f"{bm} {f(fin[bm])}"; sp = fin[bm] / ours; lb = ""
            else:
                best = "none$^{\\dagger}$"; sp = 900 / ours; lb = ">"
            rows.append((ds, c, p, st.mean(sz), ours, kd, best, sp, lb))
            print(ds, c, p, "|R|", st.mean(sz), "ours", round(ours, 3), "KD-PA", round(kd, 3), best, "speedup",
                  lb + f"{sp:.1f}", "bound/engine", round(ours / kd, 2))
print("folds compared:", n_cmp, "all exact methods agree:", agree_all)

L = [r"\begin{table}[pos=!htbp]", r"\centering",
     r"\caption{The two tables dropped at screening: mean reduction time (seconds, five folds) of the $k$-d tree engine"
     r" with and without the bound and of the fastest existing exact method, and the speed-up of KD-PA+B3 over it."
     r" $|R|$: mean reduct size. $^{\dagger}$No existing exact method finished;"
     r" the speed-up is a lower bound computed with $900$\,s.}",
     r"\label{tab:excluded}", r"\small", r"\begin{tabular}{llrrrrlr}", r"\toprule",
     r"Dataset & Criterion & Param. & $|R|$ & KD-PA+B3 & KD-PA & Fastest existing & Speed-up \\", r"\midrule"]
prev = None
for ds, c, p, sz, ours, kd, best, sp, lb in rows:
    name = NAME[ds] if ds != prev else ""; prev = ds
    par = f"$\\delta={p}$" if c == "NRS" else (r"$\sigma=0.25$" if p == "0.25" else r"$\sigma=$ std")
    L.append(f"{name} & {c} & {par} & {sz:.1f} & {f(ours)} & {f(kd)} & {best} & ${lb}{(f'{sp:.2f}' if sp < 1 else f'{sp:.1f}')}$ \\\\")
L += [r"\bottomrule", r"\end{tabular}", r"\end{table}"]
open(OUT, "w").write("% generated by revision_R1/analysis/make_tab_excluded.py from code/excluded/excluded_run.jsonl\n"
                     + "\n".join(L) + "\n")
print("wrote", OUT)
