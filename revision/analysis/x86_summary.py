"""R1.20: the subset of 34 units (fold 1) run on an x86 laptop and on the M4 Pro with the same script
(x86_check/run_check.py), the same locked engines and the same data.

Sources: x86_check/results/x86_results.jsonl (Intel Core i7-1165G7, Windows 11, 2026-11-25) and
x86_check/reference/m4_reference.jsonl (Apple M4 Pro, 2026-11-24). Speed-up = time(first) / time(second), pairs whose
second method took > 0.5 s on the M4. A pair whose first method timed out on x86 gives a lower bound (1800 s cap).

python x86_summary.py         -> facts on stdout
python x86_summary.py --tex   -> also writes manuscript/tab_x86.tex
"""
import json, os, statistics as st, sys

HERE = os.path.dirname(os.path.abspath(__file__))
X86 = os.path.join(HERE, "..", "x86_check", "results", "x86_results.jsonl")
M4 = os.path.join(HERE, "..", "x86_check", "reference", "m4_reference.jsonl")
TEX = os.path.join(HERE, "..", "manuscript", "tab_x86.tex")
CAP = 1800
PAIRS = (("KD-PA", "KD-PA+B3"), ("FNC", "FNC+B3"), ("FNC", "KD-PA+B3"), ("HASH", "KD-PA+B3"), ("FA-FPR", "KD-PA+B3"))

key = lambda r: (r["dataset"], r["criterion"], str(r["param"]), r["method"])
X = {key(r): r for r in map(json.loads, open(X86))}
M = {key(r): r for r in map(json.loads, open(M4))}
assert set(X) == set(M) and len(X) == 34
ok = lambda Z, q: Z[q]["status"] == "ok"
both = [q for q in X if ok(X, q) and ok(M, q)]
same_R = sum(X[q]["R"] == M[q]["R"] for q in both)
same_e = [q for q in both if X[q]["evals"] == M[q]["evals"]]
tr = [X[q]["time"] / M[q]["time"] for q in both if M[q]["time"] > 0.5]
print(f"units 34; finished on both {len(both)}; same ordered reduct {same_R}; same number of evaluations {len(same_e)}")
for q in both:
    if X[q]["evals"] != M[q]["evals"]:
        print("  evaluations differ:", q, "x86", X[q]["evals"], "M4", M[q]["evals"])
for q in X:
    if not ok(X, q):
        print("  not finished on x86:", q, X[q]["status"], round(X[q]["time"], 1), "s; M4", round(M[q]["time"], 1), "s")
print(f"time x86/M4: median {st.median(tr):.2f}, range {min(tr):.2f}-{max(tr):.2f} (n={len(tr)})")

rows, rat = [], []
for q in sorted(X, key=lambda q: (q[1], q[0])):
    d, c, p, a = q
    for a1, b1 in PAIRS:
        if a != a1 or (d, c, p, b1) not in X:
            continue
        qb = (d, c, p, b1)
        if not (ok(M, q) and ok(M, qb) and ok(X, qb)) or M[qb]["time"] <= 0.5:
            continue
        sm = M[q]["time"] / M[qb]["time"]
        if ok(X, q):
            sx, lb = X[q]["time"] / X[qb]["time"], False
            rat.append(sx / sm)
        else:
            sx, lb = CAP / X[qb]["time"], True
        rows.append((d, c, a1, b1, sm, sx, lb))
full = [r for r in rows if not r[6]]
print(f"speed-up pairs with both finished: {len(full)}; x86/M4 ratio of speed-ups median {st.median(rat):.2f}, "
      f"range {min(rat):.2f}-{max(rat):.2f}")
far = [r for r in full if abs(r[4] - 1) > 0.1]
print(f"pairs with M4 speed-up off 1 by >10%: {len(far)}; same side of 1 on x86: "
      f"{sum((r[4] > 1) == (r[5] > 1) for r in far)}")
for r in sorted(full, key=lambda r: r[5] / r[4]):
    print(f"  {r[0]:18s} {r[1]} {r[2]:6s}/{r[3]:8s} M4 {r[4]:7.2f}  x86 {r[5]:7.2f}  ratio {r[5] / r[4]:.2f}")
for r in rows:
    if r[6]:
        print(f"  lower bound: {r[0]} {r[1]} {r[2]}/{r[3]} M4 {r[4]:.1f}, x86 > {r[5]:.1f}")

if "--tex" in sys.argv:
    L = ["% generated by revision_R1/analysis/x86_summary.py --tex; do not edit",
         "\\begin{table}[pos=htbp]",
         "\\caption{Speed-ups on the ARM machine of the main runs and on an x86 machine: time of the first method over "
         "time of the second, fold~1, one unit at a time.}\\label{tab:x86}",
         "\\centering\\small", "\\begin{tabular}{llllrr}", "\\toprule",
         "Dataset & Criterion & First & Second & ARM & x86 \\\\", "\\midrule"]
    for d, c, a, b, sm, sx, lb in rows:
        L.append(f"{d} & {c} & {a} & {b} & {sm:.2f} & " + (f"$>{sx:.1f}$" if lb else f"{sx:.2f}") + " \\\\")
    L += ["\\bottomrule", "\\end{tabular}",
          "\\par\\smallskip\\footnotesize $>$: the first method exceeded $1800$\\,s on the x86 machine (lower bound).",
          "\\end{table}"]
    open(TEX, "w").write("\n".join(L) + "\n")
    print("wrote", TEX)
