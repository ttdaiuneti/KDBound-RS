"""Fig. 3 (revision): Nemenyi CD diagrams with one block per dataset (R2.1). Reads e1/e1_raw.jsonl only.
Writes ../manuscript/fig_cd.tex and stats_dataset_level.txt."""
import json, os, sys, statistics as st
from collections import defaultdict
import numpy as np
from scipy import stats
HERE = os.path.dirname(os.path.abspath(__file__)); E1 = os.path.join(HERE, "..", "..", "e1"); sys.path.insert(0, E1)
from run_e1 import superseded, is_superseded, LIMIT
from stats_e1 import MAIN, Q05

sup = superseded(); T = defaultdict(lambda: defaultdict(dict)); zero = set()
for r in map(json.loads, open(os.path.join(E1, "e1_raw.jsonl"))):
    if is_superseded(r, sup) or r["status"] != "ok": continue
    k = (r["dataset"], r["criterion"], r["param"]); T[k][r["method"]][r["fold"]] = r["time"]
    if r["method"] != "FARA" and len(r["R"]) == 0: zero.add(k)
blocks = sorted(k for k in T if len(T[k].get("KD-PA+B3", {})) == 5 and k not in zero)
full = lambda k, m: st.mean(T[k][m].values()) if len(T[k].get(m, {})) == 5 else None

def analyse(crit):
    meths = MAIN[crit]; ds = sorted({k[0] for k in blocks if k[1] == crit})
    M = np.array([[np.exp(np.mean([np.log(full(k, m) or LIMIT) for k in blocks if k[1] == crit and k[0] == d]))
                   for m in meths] for d in ds])
    chi, p = stats.friedmanchisquare(*M.T)
    R = np.mean([stats.rankdata(row) for row in M], axis=0)
    cd = Q05[len(meths)] * np.sqrt(len(meths) * (len(meths) + 1) / (6 * len(ds)))
    nconf = sum(1 for k in blocks if k[1] == crit)
    return len(ds), nconf, chi, p, cd, sorted(zip(meths, R), key=lambda x: x[1])

def tikz(crit, x0=0):
    nb, nconf, chi, p, cd, ranks = analyse(crit)
    k = len(ranks); sc = 2.0; X = lambda r: round(x0 + (r - 1) * sc, 3)
    s = [f"% {crit}: {nb} datasets ({nconf} configurations), Friedman chi2 = {chi:.2f}, p = {p:.2e}, CD = {cd:.2f}",
         f"\\draw ({X(1)},0) -- ({X(k)},0);"]
    for i in range(1, k + 1):
        s.append(f"\\draw ({X(i)},0) -- ({X(i)},0.12) node[above]{{\\scriptsize {i}}};")
    s.append(f"\\draw[|-|] ({X(1)},0.75) -- ({round(X(1) + cd * sc, 3)},0.75) node[midway,above]{{\\scriptsize CD = {cd:.2f}}};")
    half = (k + 1) // 2
    for j, (m, r) in enumerate(ranks):
        y = round(-0.45 - 0.38 * (j if j < half else k - 1 - j), 3)
        xe, anc = (X(1) - 0.3, "east") if j < half else (X(k) + 0.3, "west")
        col = "cBound, line width=1.1pt" if m.startswith("KD-PA") else "cMuted"
        s.append(f"\\draw[{col}] ({X(r)},0) |- ({xe},{y}) node[anchor={anc}, text=black]{{\\scriptsize {m} ({r:.2f})}};")
    rs = sorted(r for _, r in ranks); cl = []
    for i in range(k):
        j = i
        while j + 1 < k and rs[j + 1] - rs[i] < cd: j += 1
        if j > i and not any(a <= i and j <= b for a, b in cl): cl.append((i, j))
    for n, (i, j) in enumerate(cl):
        y = round(-0.18 - 0.12 * n, 3)
        s.append(f"\\draw[line width=1.6pt] ({round(X(rs[i]) - 0.05, 3)},{y}) -- ({round(X(rs[j]) + 0.05, 3)},{y});")
    mant, ex = f"{p:.1e}".split("e")
    s.append(f"\\node at ({X((k + 1) / 2)},1.25) {{\\small {crit} ({nb} datasets, Friedman $p={mant}\\times10^{{{int(ex)}}}$)}};")
    return "\n".join(s), (nb, nconf, chi, p, cd, ranks)

nrs, a = tikz("NRS"); frs, b = tikz("FRS")
open(os.path.join(HERE, "..", "manuscript", "fig_cd.tex"), "w").write(
    "% generated by make_fig_cd_dataset.py from e1_raw.jsonl -- do not edit by hand\n\\begin{tikzpicture}\n" + nrs +
    "\n\\begin{scope}[yshift=-3.5cm]\n" + frs + "\n\\end{scope}\n\\end{tikzpicture}\n")
with open(os.path.join(HERE, "stats_dataset_level.txt"), "w") as f:
    for crit, (nb, nconf, chi, p, cd, ranks) in (("NRS", a), ("FRS", b)):
        line = f"{crit}: {nb} datasets ({nconf} configurations), chi2 = {chi:.2f}, p = {p:.2e}, CD = {cd:.2f}; " + \
               ", ".join(f"{m} {r:.2f}" for m, r in ranks)
        print(line); f.write(line + "\n")
