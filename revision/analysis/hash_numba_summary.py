"""R2.3: summary of code/impl/hash_numba.jsonl (compiled HASH vs NumPy HASH, KD-PA, KD-PA+B3; NRS, delta = 0.10,
fold 1, one unit at a time, 900 s cap).

vehicle-sensit KD-PA+B3: the timed run finished but the record failed when comparing with e1_raw.jsonl, where that
unit had exceeded 900 s under concurrency. Its time is taken from e1/remeasure_idle.jsonl (idle re-measurement, same
protocol), marked with a dagger.

python hash_numba_summary.py          -> summary on stdout
python hash_numba_summary.py --tex    -> also writes manuscript/tab_hashnb.tex
"""
import json, os, statistics as st, sys

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, "..", "code", "impl", "hash_numba.jsonl")
IDLE = os.path.join(HERE, "..", "..", "e1", "remeasure_idle.jsonl")
TEX = os.path.join(HERE, "..", "manuscript", "tab_hashnb.tex")
LIMIT = 900
ORDER = ("mammography", "htru2", "magic-telescope", "house-16h", "creditcard", "internet-firewall", "run-or-walk",
         "hls4ml-jets", "gas-drift", "jannis", "miniboone", "vehicle-sensit")
METHODS = ("KD-PA", "KD-PA+B3", "HASH-NB", "HASH")

T, SAME, COMP, FIX = {}, {}, [], set()
for r in map(json.loads, open(SRC)):
    k = (r["dataset"], r["method"])
    T[k] = r["time"] if r["status"] == "ok" else None
    if r["status"] == "ok":
        SAME[k] = r["same_as_e1"]
    if r.get("compile_s") is not None:
        COMP.append(r["compile_s"])
for r in map(json.loads, open(IDLE)):
    if (r["dataset"], r["criterion"], r["param"], r["fold"], r["method"], r["status"]) == \
            ("vehicle-sensit", "NRS", "0.10", 1, "KD-PA+B3", "ok") and T.get(("vehicle-sensit", "KD-PA+B3")) is None:
        T[("vehicle-sensit", "KD-PA+B3")] = r["time"]; FIX.add(("vehicle-sensit", "KD-PA+B3"))

assert all((s, m) in T for s in ORDER for m in METHODS), "missing units"


def ratio(a, b):
    """time(a)/time(b); a lower bound '>' when a timed out and b finished; None otherwise."""
    if a is not None and b is not None:
        return a / b, ""
    if a is None and b is not None:
        return LIMIT / b, ">"
    return None, ""


rows, impl, vs_kd, vs_b3 = [], [], [], []
for s in ORDER:
    t = {m: T[(s, m)] for m in METHODS}
    r1 = ratio(t["HASH"], t["HASH-NB"]); r2 = ratio(t["HASH-NB"], t["KD-PA"]); r3 = ratio(t["HASH-NB"], t["KD-PA+B3"])
    if r1[0] is not None and not r1[1]: impl.append(r1[0])
    if r2[0] is not None and not r2[1]: vs_kd.append(r2[0])
    if r3[0] is not None and not r3[1]: vs_b3.append(r3[0])
    rows.append((s, t, r1, r2, r3))

n_same = sum(SAME.values()); n_ok = len(SAME)
print(f"units ok {n_ok}, reduct same as e1 {n_same}")
print(f"compile time on the 200-object sample: {min(COMP):.2f}-{max(COMP):.2f} s (not in the timed runs)")
for s, t, r1, r2, r3 in rows:
    f = lambda x: "  >900" if x is None else f"{x:7.1f}"
    g = lambda r: "     -" if r[0] is None else f"{r[1]:1s}{r[0]:5.1f}"
    print(f"{s:18s} KD {f(t['KD-PA'])} B3 {f(t['KD-PA+B3'])} NB {f(t['HASH-NB'])} HASH {f(t['HASH'])} | "
          f"HASH/NB {g(r1)}  NB/KD {g(r2)}  NB/B3 {g(r3)}")
print(f"HASH/HASH-NB (both finished, n={len(impl)}): median {st.median(impl):.1f}, range {min(impl):.1f}-{max(impl):.1f}")
print(f"HASH-NB/KD-PA (both finished, n={len(vs_kd)}): median {st.median(vs_kd):.1f}, range {min(vs_kd):.1f}-{max(vs_kd):.1f}")
print(f"HASH-NB/KD-PA+B3 (both finished, n={len(vs_b3)}): median {st.median(vs_b3):.1f}, "
      f"range {min(vs_b3):.1f}-{max(vs_b3):.1f}")
print("KD-PA faster than HASH-NB on", sum(1 for _, t, _, r, _ in rows if r[0] is not None and r[0] > 1),
      "of", sum(1 for _, t, _, r, _ in rows if r[0] is not None), "tables with a ratio")
print("KD-PA+B3 faster than HASH-NB on", sum(1 for _, t, _, _, r in rows if r[0] is not None and r[0] > 1),
      "of", sum(1 for _, t, _, _, r in rows if r[0] is not None), "tables with a ratio")

if "--tex" in sys.argv:
    def cell(s, m):
        x = T[(s, m)]
        return "$>900$" if x is None else (f"{x:.1f}" + ("$^\\dagger$" if (s, m) in FIX else ""))

    def rc(r):
        return "--" if r[0] is None else (f"$>{r[0]:.1f}$" if r[1] else f"{r[0]:.1f}")
    L = ["% generated by revision_R1/analysis/hash_numba_summary.py --tex; do not edit",
         "\\begin{table}[pos=htbp]",
         "\\caption{Compiled HASH (HASH-NB) against the NumPy HASH, KD-PA and KD-PA+B3: time of a full reduction (s), "
         "NRS, $\\delta=0.10$, fold~1, one unit at a time.}\\label{tab:hashnb}",
         "\\centering\\small",
         "\\begin{tabular}{lrrrrrrr}", "\\toprule",
         "Dataset & KD-PA & KD-PA+B3 & HASH-NB & HASH & $\\frac{\\text{HASH}}{\\text{HASH-NB}}$ & "
         "$\\frac{\\text{HASH-NB}}{\\text{KD-PA}}$ & $\\frac{\\text{HASH-NB}}{\\text{KD-PA+B3}}$ \\\\", "\\midrule"]
    for s, t, r1, r2, r3 in rows:
        L.append(f"{s} & {cell(s, 'KD-PA')} & {cell(s, 'KD-PA+B3')} & {cell(s, 'HASH-NB')} & {cell(s, 'HASH')} & "
                 f"{rc(r1)} & {rc(r2)} & {rc(r3)} \\\\")
    L += ["\\bottomrule", "\\end{tabular}",
          "\\par\\smallskip\\footnotesize $>900$: exceeded the 900\\,s limit; a ratio with $>$ is a lower bound. "
          "$^\\dagger$Idle re-measurement of Section~\\ref{sec:exp:setup}.",
          "\\end{table}"]
    open(TEX, "w").write("\n".join(L) + "\n")
    print("wrote", TEX)

# Part 2 (added 2026-11-24): the five tables with m >= 29 at every delta (delta = 0.10 from hash_numba.jsonl, the
# others from hash_numba_delta.jsonl, fold 1). Ratio = time(HASH-NB) / time(KD-PA+B3); '>' when HASH-NB exceeded 900 s.
HI = ("creditcard", "miniboone", "jannis", "vehicle-sensit", "gas-drift")
PS = ("0.05", "0.10", "0.15", "0.20")
D = {}
for r in map(json.loads, open(os.path.join(HERE, "..", "code", "impl", "hash_numba_delta.jsonl"))):
    D[(r["dataset"], r["param"], r["method"])] = (r["time"] if r["status"] == "ok" else None, r.get("same_as_e1"))
for s in HI:
    for m in ("KD-PA+B3", "HASH-NB"):
        D[(s, "0.10", m)] = (T[(s, m)], SAME.get((s, m), True if (s, m) in FIX else None))
R2, cells, n_same, n_ok = [], {}, 0, 0
for s in HI:
    for p in PS:
        b, nb = D[(s, p, "KD-PA+B3")][0], D[(s, p, "HASH-NB")][0]
        for m in ("KD-PA+B3", "HASH-NB"):
            t, sm = D[(s, p, m)]
            if t is not None and (s, m) not in FIX:
                n_ok += 1; n_same += bool(sm)
        r = ratio(nb, b)
        cells[(s, p)] = r
        if r[0] is not None:
            R2.append(r)
vals = [v for v, _ in R2]
print(f"\nm >= 29, all deltas: {len(R2)} settings with a ratio, {sum(1 for _, g in R2 if g)} lower bounds; "
      f"HASH-NB slower in {sum(v > 1 for v in vals)}; median {st.median(vals):.1f} (lower bounds at their value), "
      f"range {min(vals):.1f}-{max(vals):.1f}; reducts same as e1 {n_same}/{n_ok} timed ok units")
for s in HI:
    print(f"{s:16s} " + "  ".join(f"{p}: " + ("   -  " if cells[(s, p)][0] is None else
                                               f"{cells[(s, p)][1]:1s}{cells[(s, p)][0]:5.1f}") for p in PS))
if "--tex" in sys.argv:
    L = ["% generated by revision_R1/analysis/hash_numba_summary.py --tex; do not edit",
         "\\begin{table}[pos=htbp]",
         "\\caption{Time of the compiled HASH (HASH-NB) over the time of KD-PA+B3 on the tables with $m\\ge29$, NRS, "
         "fold~1, one unit at a time.}\\label{tab:hashnb:delta}",
         "\\centering\\small", "\\begin{tabular}{lrrrrr}", "\\toprule",
         "Dataset & $m$ & $\\delta=0.05$ & $0.10$ & $0.15$ & $0.20$ \\\\", "\\midrule"]
    MM = {"creditcard": 29, "miniboone": 50, "jannis": 54, "vehicle-sensit": 100, "gas-drift": 128}
    for s in HI:
        L.append(f"{s} & ${MM[s]}$ & " + " & ".join(rc(cells[(s, p)]) for p in PS) + " \\\\")
    L += ["\\bottomrule", "\\end{tabular}",
          "\\par\\smallskip\\footnotesize $>$: HASH-NB exceeded $900$\\,s (lower bound). --: KD-PA+B3 also exceeded "
          "$900$\\,s.", "\\end{table}"]
    open(os.path.join(HERE, "..", "manuscript", "tab_hashnb_delta.tex"), "w").write("\n".join(L) + "\n")
    print("wrote tab_hashnb_delta.tex")
