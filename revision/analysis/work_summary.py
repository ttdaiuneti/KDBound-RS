"""R2.3: split the time ratio engine / KD-PA along the greedy path into a work ratio (pairs examined, machine
independent) and a cost ratio (time per pair examined). time ratio = work ratio x cost ratio.
Inputs: code/impl/work_count.jsonl (KD counts, CABIN windows, FNC, FRS) and code/baselines/hash_audit_path.jsonl
(times and pairs of HASH-G, CABIN, BUCKET, BF-PA, KD-PA). Only datasets on which both engines finished the path.
python work_summary.py [--box]
"""
import json
import os
import statistics as st
import sys
from collections import defaultdict

HERE = os.path.dirname(os.path.abspath(__file__))
WC = os.path.join(HERE, "..", "code", "impl", "work_count.jsonl")
HA = os.path.join(HERE, "..", "code", "baselines", "hash_audit_path.jsonl")
KEY = "box" if "--box" in sys.argv else "cell"

def load(KEY):
    work = defaultdict(lambda: defaultdict(float)); tim = defaultdict(lambda: defaultdict(float))
    steps = defaultdict(lambda: defaultdict(int)); bad = set(); length = {}
    for ln in open(HA):
        r = json.loads(ln); k = (r["dataset"], "NRS")
        if "step" not in r:
            bad.add((k, r["engine"])); continue
        e = r["engine"]
        if e == "HASH-B7":
            continue
        if e == "KD-PA":
            tim[k]["KD"] += r["time"]; steps[k]["KD-t"] += 1
        else:
            tim[k][e] += r["time"]; steps[k][e] += 1
            if e in ("HASH-G", "BUCKET"):
                work[k][e] += r["pairs"]                 # BF-PA work (|act| x n) is added from the KD-count rows
    for ln in open(WC):
        r = json.loads(ln); k = (r["dataset"], r["crit"]); u = r["unit"]
        if "step" not in r:
            bad.add((k, {"FNC": "FNC", "FRS-FA": "FA-FPR", "FRS-KD": "KD", "KD-count": "KD", "CABIN-win": "CABIN"}[u]))
            continue
        if u == "KD-count":
            work[k]["KD"] += r[KEY] + r["confirm"]; steps[k]["KD-w"] += 1; length[k] = max(length.get(k, 0), r["step"])
            work[k]["BF-PA"] += r["active"] * r["n"]
        elif u == "CABIN-win":
            work[k]["CABIN"] += r["window"]; steps[k]["CABIN-w"] += 1
        elif u == "FNC" and r["step"] >= 1:
            work[k]["FNC"] += r["pairs"]; tim[k]["FNC"] += r["time"]; steps[k]["FNC"] += 1
        elif u == "FRS-KD":
            work[k]["KD"] += r[KEY] + r["confirm"]; tim[k]["KD"] += r["time"]; steps[k]["KD-w"] += 1; steps[k]["KD-t"] += 1
            length[k] = max(length.get(k, 0), r["step"])
        elif u == "FRS-FA":
            work[k]["FA-FPR"] += r["pairs"]; tim[k]["FA-FPR"] += r["time"]; steps[k]["FA-FPR"] += 1
    return work, tim, steps, bad, length


work, tim, steps, bad, length = load(KEY)
ENG = {"NRS": ("HASH-G", "FNC", "CABIN", "BUCKET", "BF-PA"), "FRS": ("FA-FPR",)}


def rows_of(crit, e, D=None):
    work, tim, steps, bad, length = D or (globals()['work'], globals()['tim'], globals()['steps'], globals()['bad'], globals()['length'])
    rows = {}
    for k in sorted(work):
        if k[1] != crit or k not in length:
            continue
        L = length[k]
        if (k, e) in bad or (k, "KD") in bad or steps[k]["KD-w"] != L or steps[k]["KD-t"] != L or steps[k][e] != L:
            continue
        wr = work[k][e] / work[k]["KD"]; tr = tim[k][e] / tim[k]["KD"]
        rows[k[0]] = (wr, tr, tr / wr, work[k]["KD"], tim[k]["KD"])
    return rows


if "--tex" not in sys.argv:
    print(f"count = {KEY}; ratios engine / KD-PA, summed over the path (one evaluation per step)")
    for crit in ("NRS", "FRS"):
        for e in ENG[crit]:
            rows = rows_of(crit, e)
            if not rows:
                continue
            print(f"\n{crit} {e}: {len(rows)} datasets")
            print(f"  {'dataset':20s} {'work':>9s} {'time':>9s} {'cost':>8s}   KD pairs   KD time")
            for d, (wr, tr, cr, w, t) in rows.items():
                print(f"  {d:20s} {wr:9.3g} {tr:9.3g} {cr:8.3g}  {w:9.3g} {t:9.3g}")
            v = list(rows.values())
            print(f"  median work ratio {st.median(r[0] for r in v):.3g} (range {min(r[0] for r in v):.3g}-{max(r[0] for r in v):.3g}),"
                  f" time ratio {st.median(r[1] for r in v):.3g}, cost ratio {st.median(r[2] for r in v):.3g}"
                  f" (range {min(r[2] for r in v):.3g}-{max(r[2] for r in v):.3g}); work ratio > 1 on {sum(r[0] > 1 for r in v)},"
                  f" cost ratio > 1 on {sum(r[2] > 1 for r in v)}")
else:
    OUTT = os.path.join(HERE, "..", "manuscript", "tab_work.tex")
    N = {e: rows_of("NRS", e) for e in ("HASH-G", "FNC", "CABIN", "BF-PA")}; F = rows_of("FRS", "FA-FPR")
    kdn = {d: r[3] for d, r in N["HASH-G"].items()}; kdf = {d: r[3] for d, r in F.items()}
    order = sorted(set(kdn) | set(kdf), key=lambda d: (kdn.get(d, kdf.get(d)), d))

    def f(x):
        return "--" if x is None else (f"{x:.0f}" if x >= 99.5 else (f"{x:.1f}" if x >= 0.995 else f"{x:.2f}"))

    def m(x):
        return "--" if x is None else (f"{x / 1e6:.0f}" if x >= 9.95e6 else f"{x / 1e6:.1f}")
    L = ["% generated by revision_R1/analysis/work_summary.py --tex from code/impl/work_count.jsonl and",
         "% code/baselines/hash_audit_path.jsonl",
         "\\begin{table}[pos=!htbp]", "\\centering",
         "\\caption{Pairs examined and time per pair along the greedy path (fold~1; NRS $\\delta=0.10$, FRS "
         "$\\sigma=0.25$). KD-PA: pairs examined (cell count), in millions. w and c: ratios to KD-PA (Appendix~\\ref{sec:appendix:audit}). "
         "--: not finished or not run.}",
         "\\label{tab:work}", "\\small", "\\setlength{\\tabcolsep}{3.5pt}",
         "\\begin{tabular}{l r rr rr rr rr r rr}", "\\toprule",
         " & \\multicolumn{9}{c}{NRS} & \\multicolumn{3}{c}{FRS} \\\\",
         "\\cmidrule(lr){2-10}\\cmidrule(lr){11-13}",
         " & KD-PA & \\multicolumn{2}{c}{HASH} & \\multicolumn{2}{c}{FNC} & \\multicolumn{2}{c}{CABIN} & \\multicolumn{2}{c}{BF-PA} "
         "& KD-PA & \\multicolumn{2}{c}{FA-FPR} \\\\",
         "\\cmidrule(lr){3-4}\\cmidrule(lr){5-6}\\cmidrule(lr){7-8}\\cmidrule(lr){9-10}\\cmidrule(lr){12-13}",
         "Dataset & pairs & w & c & w & c & w & c & w & c & pairs & w & c \\\\", "\\midrule"]
    for d in order:
        c = [d, m(kdn.get(d))]
        for e in ("HASH-G", "FNC", "CABIN", "BF-PA"):
            r = N[e].get(d); c += [f(r[0]) if r else "--", f(r[2]) if r else "--"]
        r = F.get(d); c += [m(kdf.get(d)), f(r[0]) if r else "--", f(r[2]) if r else "--"]
        L.append(" & ".join(c) + " \\\\")
    L.append("\\midrule")
    c = ["Median, cell count", ""]
    for e in ("HASH-G", "FNC", "CABIN", "BF-PA"):
        v = list(N[e].values()); c += [f(st.median(r[0] for r in v)), f(st.median(r[2] for r in v))]
    v = list(F.values()); c += ["", f(st.median(r[0] for r in v)), f(st.median(r[2] for r in v))]
    L.append(" & ".join(c) + " \\\\")
    DB = load("box"); c = ["Median, box count", ""]
    for e in ("HASH-G", "FNC", "CABIN", "BF-PA"):
        v = list(rows_of("NRS", e, DB).values()); c += [f(st.median(r[0] for r in v)), f(st.median(r[2] for r in v))]
    v = list(rows_of("FRS", "FA-FPR", DB).values()); c += ["", f(st.median(r[0] for r in v)), f(st.median(r[2] for r in v))]
    L += [" & ".join(c) + " \\\\", "\\bottomrule", "\\end{tabular}", "\\end{table}"]
    open(OUTT, "w").write("\n".join(L) + "\n")
    print("wrote", OUTT)
