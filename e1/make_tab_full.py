"""Generate paper/manuscript/tab_full.tex (Appendix: every configuration, mean time over five folds) from
e1_raw.jsonl (superseded rows excluded). T: exceeded 900 s on fold 1; M: memory limit on fold 1; d: degenerate."""
import collections
import json
import os
import statistics as st

from run_e1 import superseded, is_superseded
from data_e1 import DATASETS

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "paper", "manuscript", "tab_full.tex")
sup = superseded(); T = collections.defaultdict(dict); ST = {}; RL = collections.defaultdict(list)
for r in map(json.loads, open(os.path.join(HERE, "e1_raw.jsonl"))):
    if is_superseded(r, sup):
        continue
    k = (r["dataset"], r["criterion"], r["param"], r["method"])
    if r["fold"] == 1:
        ST[k] = r["status"]
    if r["status"] == "ok":
        T[k][r["fold"]] = r["time"]
        if r["method"] == "KD-PA+B3":
            RL[k[:3]].append(len(r["R"]))


def c(k):
    t = T[k]
    if len(t) == 5:
        v = st.mean(t.values()); s = st.stdev(t.values())
        return (f"{v:.2f}" if v < 10 else f"{v:.1f}" if v < 100 else f"{v:.0f}")
    return {"timeout": "T", "memout": "M"}.get(ST.get(k), "--")


def block(crit, params, meths, head):
    rows = []
    for ds in DATASETS:
        for p in params:
            if (ds, crit, p, "KD-PA+B3") not in ST:
                continue
            R = RL[(ds, crit, p)]
            rl = (f"{st.mean(R):.1f}" + ("$^d$" if 0 in R else "")) if len(R) == 5 else "--"
            rows.append(f"{ds} & {p} & " + " & ".join(c((ds, crit, p, m)) for m in meths) + f" & {rl} \\\\")
    cols = "@{}ll" + "r" * (len(meths) + 1) + "@{}"
    sym = "$\\delta$" if crit == "NRS" else "$\\sigma$"
    return (f"\\begin{{longtable}}{{{cols}}}\n\\caption{{{head}}}\\\\\n\\toprule\n"
            "Dataset & " + sym + " & " + " & ".join(meths) + " & $|R|$ \\\\\n\\midrule\n\\endhead\n"
            + "\n".join(rows) + "\n\\bottomrule\n\\end{longtable}\n")


cap = ("{c}: mean reduction time over five folds (seconds) for every configuration. T: exceeded $900$\\,s on fold~1; "
       "M: memory limit on fold~1; --: finished fold~1 but not all five folds; $|R|$: mean size of the exact reduct; $^d$: degenerate (an empty reduct in some fold).")
body = ("% generated by e1/make_tab_full.py from e1/e1_raw.jsonl -- do not edit by hand\n{\\small\\setlength{\\tabcolsep}{4pt}\n"
        + block("NRS", ["0.05", "0.10", "0.15", "0.20"], ["KD-PA+B3", "KD-PA", "FNC", "FNC+B3", "HASH", "FARA"],
                cap.format(c="NRS") + "\\label{tab:full-nrs}")
        + block("FRS", ["0.25", "std"], ["KD-PA+B3", "KD-PA", "FA-FPR", "FA-FPR+B3"],
                cap.format(c="FRS") + "\\label{tab:full-frs}") + "}\n")
open(OUT, "w").write(body)
print(body.count("\\\\") , "lines")
