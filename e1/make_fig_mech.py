"""Illustration of the witness bound (manuscript Fig. "mechanism"), panel (b) from one real greedy step.

gas-drift, NRS, delta = 0.10, fold 1 (training part), KD-PA engine. The exact greedy is run for STEP steps; at the
next step the witness bound UB(a) and, for illustration only, the exact significance sig(a, R) of EVERY candidate are
computed. The pruned scan (Definition "pruned step") is replayed with the running best g*, so the evaluated set is
exactly the one Algorithm 2 evaluates. Checks: UB(a) >= sig(a) for all a, and the selected attribute equals the greedy
choice. Panel (a) is a schematic (TikZ, no data). Output: ../paper/manuscript/fig_mech.tex (+ printed numbers).
"""
import os
import sys

import numpy as np

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from data_e1 import load            # noqa: E402
from run_e1 import folds            # noqa: E402
from engines_e1 import KD, bound_ub  # noqa: E402

SLUG, DELTA, STEP = "gas-drift", 0.10, 4
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "paper", "manuscript", "fig_mech.tex")

X, y = load(SLUG); tr = folds(y)[0][0]; X, y = X[tr], y[tr]
eng = KD(X, y, DELTA); n, d = X.shape
act = np.arange(n); R, rem = [], list(range(d))
for t in range(STEP):                                     # exact greedy (index tie-break), positive approximation
    g = {a: int(len(act) - eng.blocked(R + [a], act).sum()) for a in rem}
    best = min(rem, key=lambda a: (-g[a], a))
    R.append(best); rem.remove(best); act = act[eng.blocked(R, act)]

ub = bound_ub(X, act, eng.witness(R, act), R, rem, eng.d2)
sig = {a: int(len(act) - eng.blocked(R + [a], act).sum()) for a in rem}
order = sorted(rem, key=lambda a: (-ub[a], a))
gstar, astar, evaluated = 0, None, []
for a in order:                                           # replay of the pruned scan with the running best
    if ub[a] < max(gstar, 1):
        break
    evaluated.append(a)
    if sig[a] > gstar or (sig[a] == gstar and sig[a] > 0 and a < astar):
        gstar, astar = sig[a], a
greedy_choice = min(rem, key=lambda a: (-sig[a], a))
assert all(ub[a] >= sig[a] for a in rem) and astar == greedy_choice
print(f"{SLUG} delta={DELTA} fold 1, step {STEP + 1}: |R|={len(R)} |A|={len(act)} candidates={len(rem)} "
      f"evaluated={len(evaluated)} skipped={len(rem) - len(evaluated)} g*={gstar} max UB={max(ub.values())} "
      f"selected={astar} (greedy {greedy_choice}); UB>=sig for all candidates")

k = len(evaluated)
pts_ub = " ".join(f"({i + 1},{ub[a]})" for i, a in enumerate(order))
pts_ev = " ".join(f"({i + 1},{sig[a]})" for i, a in enumerate(order[:k]))
pts_sk = " ".join(f"({i + 1},{sig[a]})" for i, a in enumerate(order[k:], start=k))
ymax = int(np.ceil(max(ub.values()) / 500.0) * 500)

body = f"""% generated by e1/make_fig_mech.py -- do not edit by hand
% {SLUG}, NRS, delta={DELTA}, fold 1, step {STEP + 1}: |A|={len(act)}, {len(rem)} candidates, {k} evaluated, g*={gstar}
\\begin{{tikzpicture}}[font=\\scriptsize]
% ---------------- (a) schematic
\\begin{{scope}}[scale=1.25]
\\fill[cBound!10] (0,0) -- (1.8,0) arc (0:90:1.8) -- cycle;
\\draw[cBound, thick] (1.8,0) arc (0:90:1.8);
\\node[cBound] at (1.45,1.45) {{$\\delta$}};
\\draw[->, cMuted] (-0.2,0) -- (3.0,0);
\\node[anchor=north east] at (3.0,-0.05) {{distance on $R$}};
\\draw[->, cMuted] (0,-0.2) -- (0,2.9);
\\node[anchor=south] at (0,2.9) {{gap on the added attribute}};
\\draw[gray] (0,0) -- (1.1,0.9);
\\draw[gray] (0,0) -- (1.1,2.4);
\\draw[densely dotted] (1.1,0) -- (1.1,2.4);
\\fill (0,0) circle (1.6pt) node[below left]{{$x$}};
\\fill[cEngine] (1.1,0) circle (1.8pt) node[below=1pt]{{$\\omega_x$}};
\\draw[cEngine, fill=white] (1.1,0.9) circle (1.8pt);
\\fill[cEngine] (1.1,2.4) circle (1.8pt);
\\draw[gray!70] (1.2,0.9) -- (2.05,0.9);
\\draw[gray!70] (1.2,2.4) -- (2.05,2.4);
\\node[anchor=west, align=left] at (2.05,0.9) {{add $b$: within $\\delta$,\\\\$x$ adds $0$ to $\\mathrm{{UB}}(b)$}};
\\node[anchor=west, align=left] at (2.05,2.4) {{add $a$: beyond $\\delta$,\\\\$x$ adds $1$ to $\\mathrm{{UB}}(a)$}};
\\end{{scope}}
\\node[font=\\small, anchor=north] at (2.6,-1.5) {{(a) one object and its witness}};
% ---------------- (b) one real step
\\begin{{axis}}[at={{(7.2cm,0)}}, anchor=origin, width=7.8cm, height=5.0cm, xmin=0, xmax={len(rem) + 2}, ymin=0, ymax={ymax},
  xlabel={{candidates in decreasing order of the bound}}, ylabel={{objects}}, title={{(b) one step on gas-drift}},
  title style={{font=\\small, at={{(0.5,0)}}, anchor=north, yshift=-1.65cm}},
  tick label style={{font=\\scriptsize}}, label style={{font=\\scriptsize}}, scaled y ticks=false,
  legend style={{font=\\scriptsize, at={{(0.98,0.98)}}, anchor=north east, draw=none, fill=white, fill opacity=0.8, text opacity=1}}]
\\addplot[ycomb, cBound!45, line width=0.6pt, mark=none, legend image code/.code={{\\draw[cBound!45, line width=1.5pt] (0.1cm,-0.1cm) -- (0.1cm,0.12cm);}}] coordinates {{{pts_ub}}};
\\addplot[only marks, mark=*, mark size=1.3pt, cEngine] coordinates {{{pts_ev}}};
\\addplot[only marks, mark=o, mark size=1.2pt, cMuted] coordinates {{{pts_sk}}};
\\addplot[black, dashed, domain=0:{len(rem) + 2}] {{{gstar}}};
\\draw[densely dotted] (axis cs:{k + 0.5},0) -- (axis cs:{k + 0.5},{ymax});
\\legend{{bound $\\mathrm{{UB}}(a)$, $\\mathrm{{sig}}(a)$ evaluated, $\\mathrm{{sig}}(a)$ skipped, best $g^*$}}
\\end{{axis}}
\\end{{tikzpicture}}
"""
open(OUT, "w").write(body)
