"""Per-step view of the pruning (manuscript Section 5.4): candidates and evaluations per greedy step, and cumulative
reduction time, for KD-PA and KD-PA+B3 on one fold of two NRS configurations (delta = 0.10, fold 1):
gas-drift (m = 128, where the bound helps most) and hls4ml-jets (m = 16, where it costs most).

Source: results/reducts/<slug>__NRS__0.10__fold1__<method>.json (per-step records written by run_e1.py). Each file is
checked against the non-superseded row of e1_raw.jsonl (same time, same evaluation count, same reduct).
Output: ../paper/manuscript/fig_steps.tex (+ printed totals).
"""
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from run_e1 import superseded, is_superseded  # noqa: E402

OUT = os.path.join(HERE, "..", "paper", "manuscript", "fig_steps.tex")
CASES = (("gas-drift", 128), ("hls4ml-jets", 16))
sup = superseded()
raw = {(r["dataset"], r["criterion"], r["param"], r["fold"], r["method"]): r
       for r in map(json.loads, open(os.path.join(HERE, "e1_raw.jsonl"))) if not is_superseded(r, sup)}


def load(slug, m):
    rec = json.load(open(os.path.join(HERE, "results", "reducts", f"{slug}__NRS__0.10__fold1__{m}.json")))
    r = raw[(slug, "NRS", "0.10", 1, m)]
    assert abs(rec["time"] - r["time"]) < 1e-6 and rec["evals"] == r["evals"] and rec["R"] == r["R"], (slug, m)
    return rec


panels = []
for row, (slug, m) in enumerate(CASES):
    a, b = load(slug, "KD-PA"), load(slug, "KD-PA+B3")
    assert a["R"] == b["R"]
    sa, sb = a["steps"], b["steps"]
    cand = " ".join(f"({t + 1},{s['candidates']})" for t, s in enumerate(sb))
    ev = " ".join(f"({t + 1},{s['evaluated']})" for t, s in enumerate(sb))
    ca, cb, ta, tb = [], [], 0.0, 0.0
    for t, (x, y) in enumerate(zip(sa, sb)):
        ta += x["time"]; tb += y["time"]; ca.append(f"({t + 1},{ta:.4g})"); cb.append(f"({t + 1},{tb:.4g})")
    print(f"{slug}: steps {len(sb)}, evaluations {a['evals']} -> {b['evals']}, time {a['time']:.1f} -> {b['time']:.1f} s, "
          f"|R| = {len(b['R'])}")
    y0 = -row * 5.0
    tag = "ab"[row] if row == 0 else "cd"
    l, r = ("(a)", "(b)") if row == 0 else ("(c)", "(d)")
    panels.append(f"""\\begin{{axis}}[at={{(0,{y0}cm)}}, anchor=south west, width=0.5\\linewidth, height=4.4cm, xmin=0, xmax={len(sb) + 1},
  ymin=0, xlabel={{greedy step $t$}}, ylabel={{candidates}}, title={{{l} {slug} ($m={m}$): evaluations per step}},
  title style={{font=\\small}}, tick label style={{font=\\scriptsize}}, label style={{font=\\scriptsize}},
  legend cell align=left, legend style={{font=\\scriptsize, at={{(0.98,0.98)}}, anchor=north east, draw=none, fill=white, fill opacity=0.85, text opacity=1}}]
\\addplot[cEngine, thick, dashed, mark=none] coordinates {{{cand}}};
\\addplot[cBound, thick, mark=*, mark size={0.9 if len(sb) > 40 else 1.4}pt] coordinates {{{ev}}};
\\legend{{KD-PA (all candidates), KD-PA+B3 (evaluated)}}
\\end{{axis}}
\\begin{{axis}}[at={{(0.53\\linewidth,{y0}cm)}}, anchor=south west, width=0.5\\linewidth, height=4.4cm, xmin=0, xmax={len(sb) + 1},
  ymin=0, xlabel={{greedy step $t$}}, ylabel={{cumulative time (s)}}, title={{{r} {slug}: cumulative time}},
  title style={{font=\\small}}, tick label style={{font=\\scriptsize}}, label style={{font=\\scriptsize}},
  legend cell align=left, legend style={{font=\\scriptsize, at={{(0.02,0.98)}}, anchor=north west, draw=none, fill=white, fill opacity=0.85, text opacity=1}}]
\\addplot[cEngine, thick, dashed, mark=none] coordinates {{{' '.join(ca)}}};
\\addplot[cBound, thick, mark=none] coordinates {{{' '.join(cb)}}};
\\legend{{KD-PA, KD-PA+B3}}
\\end{{axis}}""")

body = ("% generated by e1/make_fig_steps.py from e1/results/reducts (checked against e1_raw.jsonl) -- do not edit by hand\n"
        "\\begin{tikzpicture}\n" + "\n".join(panels) + "\n\\end{tikzpicture}\n")
open(OUT, "w").write(body)
