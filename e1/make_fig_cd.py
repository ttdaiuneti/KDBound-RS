"""Generate paper/manuscript/fig_cd.tex (Nemenyi critical-difference diagrams, TikZ) from stats_e1.txt."""
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "paper", "manuscript", "fig_cd.tex")
txt = open(os.path.join(HERE, "stats_e1.txt")).read()


def block(crit):
    head = re.search(rf"{crit}: (\d+) blocks, Friedman chi2 = ([\d.]+), p = ([\de.+-]+), Nemenyi CD = ([\d.]+)", txt)
    part = txt[head.end():].split("rank gap")[0]
    ranks = [(m, float(r)) for m, r in re.findall(r"^\s+(\S+)\s+mean rank ([\d.]+)", part, re.M)]
    return int(head.group(1)), float(head.group(2)), head.group(3), float(head.group(4)), ranks


def tikz(crit, x0):
    nb, chi, p, cd, ranks = block(crit)
    k = len(ranks); sc = 2.0                                   # cm per rank unit
    X = lambda r: round(x0 + (r - 1) * sc, 3)
    s = [f"% {crit}: {nb} blocks, Friedman chi2 = {chi}, p = {p}, CD = {cd}",
         f"\\draw ({X(1)},0) -- ({X(k)},0);"]
    for i in range(1, k + 1):
        s.append(f"\\draw ({X(i)},0) -- ({X(i)},0.12) node[above]{{\\scriptsize {i}}};")
    s.append(f"\\draw[|-|] ({X(1)},0.75) -- ({round(X(1) + cd * sc, 3)},0.75) node[midway,above]{{\\scriptsize CD = {cd:.2f}}};")
    half = (k + 1) // 2
    for j, (m, r) in enumerate(ranks):
        y = round(-0.45 - 0.38 * (j if j < half else k - 1 - j), 3)
        side, xe, anc = ("left", X(1) - 0.3, "east") if j < half else ("right", X(k) + 0.3, "west")
        col = "cBound, line width=1.1pt" if m.startswith("KD-PA") else "cMuted"
        s.append(f"\\draw[{col}] ({X(r)},0) |- ({xe},{y}) node[anchor={anc}, text=black]{{\\scriptsize {m} ({r:.2f})}};")
    # cliques: maximal runs of consecutive ranks spanning less than CD
    rs = sorted(r for _, r in ranks); cl = []
    for i in range(k):
        j = i
        while j + 1 < k and rs[j + 1] - rs[i] < cd:
            j += 1
        if j > i and not any(a <= i and j <= b for a, b in cl):
            cl.append((i, j))
    for n, (i, j) in enumerate(cl):
        y = round(-0.18 - 0.12 * n, 3)
        s.append(f"\\draw[line width=1.6pt] ({round(X(rs[i]) - 0.05, 3)},{y}) -- ({round(X(rs[j]) + 0.05, 3)},{y});")
    mant, ex = f"{float(p):.1e}".split("e")
    s.append(f"\\node at ({X((k + 1) / 2)},1.25) {{\\small {crit} ({nb} configurations, Friedman $p={mant}\\times10^{{{int(ex)}}}$)}};")
    return "\n".join(s)


body = ("% generated by e1/make_fig_cd.py from e1/stats_e1.txt -- do not edit by hand\n"
        "\\begin{tikzpicture}\n" + tikz("NRS", 0) + "\n\\begin{scope}[yshift=-3.5cm]\n" + tikz("FRS", 0) +
        "\n\\end{scope}\n\\end{tikzpicture}\n")
open(OUT, "w").write(body); print(body)
