"""Supplementary scaling figure (e1_prereg.md section 13): reduction time against the number of training objects.

Source: scale_n.jsonl (scale_n.py). Checks that all exact methods that finished return the same ordered reduct at each
n, prints the log-log slope of the time of each method (least squares over the finished n), and compares n = 1e5 with
E1 fold 1. Output: ../paper/manuscript/fig_scale.tex.
"""
import json
import os
import sys
from collections import defaultdict

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from run_e1 import superseded, is_superseded, LIMIT  # noqa: E402

OUT = os.path.join(HERE, "..", "paper", "manuscript", "fig_scale.tex")
rows = [json.loads(l) for l in open(os.path.join(HERE, "scale_n.jsonl"))]
sup = superseded()
e1 = {(r["dataset"], r["criterion"], r["param"], r["method"]): r for r in map(json.loads, open(os.path.join(HERE, "e1_raw.jsonl")))
      if r["fold"] == 1 and not is_superseded(r, sup)}

PANELS = [("hls4ml-jets", "NRS", "0.10"), ("hls4ml-jets", "FRS", "0.25"), ("miniboone", "NRS", "0.10"), ("miniboone", "FRS", "0.25")]
STYLE = {"KD-PA+B3": "cBound, thick, mark=*", "KD-PA": "cEngine, thick, dashed, mark=o",
         "FNC": "black!75, mark=square", "HASH": "black!75, densely dotted, thick, mark=diamond", "FA-FPR": "black!75, mark=triangle"}

T = defaultdict(dict); RED = defaultdict(dict); NT = {}
for r in rows:
    k = (r["dataset"], r["criterion"], r["param"])
    if r["status"] == "ok":
        T[(k, r["method"])][r["n"]] = r["time"]; RED[(k, r["n"])][r["method"]] = tuple(r["R"]); NT[r["n"]] = r["n_train"]
bad = [(k, n, v) for (k, n), v in RED.items() if len(set(v.values())) > 1]
print("groups with >= 2 exact methods:", sum(len(v) > 1 for v in RED.values()), "| disagreements:", bad)
for (k, m), d in sorted(T.items()):
    ns = sorted(d)
    if len(ns) >= 2:
        sl = np.polyfit(np.log([NT[n] for n in ns]), np.log([d[n] for n in ns]), 1)[0]
        e = e1.get((*k, m)); cmp = f"; E1 fold 1 {e['time']:.1f} s" if e and e["status"] == "ok" and 100_000 in d else ""
        print(f"{k[0]:12s} {k[1]} {m:9s} times {[round(d[n], 1) for n in ns]} slope {sl:.2f}{cmp}"
              f"{f' (alone {d[100_000]:.1f} s)' if cmp else ''}")

axes = []
for i, (slug, crit, param) in enumerate(PANELS):
    k = (slug, crit, param); x0 = (i % 2) * 0.52; y0 = -(i // 2) * 5.2
    plots, leg = [], []
    for m in ("KD-PA+B3", "KD-PA", "FNC", "HASH", "FA-FPR"):
        d = T.get((k, m))
        if not d:
            continue
        c = " ".join(f"({NT[n]},{d[n]:.4g})" for n in sorted(d))
        plots.append(f"\\addplot[{STYLE[m]}, mark size=1.4pt] coordinates {{{c}}};"); leg.append(m)
    lab = f"{crit}, $\\delta={param}$" if crit == "NRS" else f"{crit}, $\\sigma={param}$"
    axes.append(f"""\\begin{{axis}}[at={{({x0}\\linewidth,{y0}cm)}}, anchor=south west, width=0.5\\linewidth, height=5.0cm, ytick={{1,10,100,1000}},
  xmode=log, ymode=log, xmin=8000, xmax=100000, ymin=0.3, ymax=60000, xlabel={{training objects}}, ylabel={{time (s)}},
  title={{({"abcd"[i]}) {slug}, {lab}}}, title style={{font=\\small}}, tick label style={{font=\\scriptsize}},
  label style={{font=\\scriptsize}}, legend cell align=left,
  legend columns=2, legend style={{font=\\scriptsize, at={{(0.02,0.98)}}, anchor=north west, draw=none, fill=white, fill opacity=0.85, text opacity=1}}]
\\addplot[gray, dashed, domain=8000:100000, forget plot] {{{LIMIT}}};
{chr(10).join(plots)}
\\legend{{{", ".join(leg)}}}
\\end{{axis}}""")
body = ("% generated by e1/make_fig_scale.py from e1/scale_n.jsonl -- do not edit by hand\n\\begin{tikzpicture}\n"
        + "\n".join(axes) + "\n\\end{tikzpicture}\n")
open(OUT, "w").write(body)
