"""Overview of the speed-up of KD-PA+B3 over the best existing exact accelerator (manuscript Section 5.3).

Source: e1_summary.csv (from summarize_e1.py). Usable configurations: not degenerate and a speed-up defined (KD-PA+B3
finished); lower bounds (no existing method finished: 900 s / mean time of KD-PA+B3) are drawn as open marks with an
upward arrow. Output: ../paper/manuscript/fig_speed.tex (+ printed counts that must match Section 5.3).
"""
import csv
import os
import statistics as st

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "paper", "manuscript", "fig_speed.tex")
rows = [r for r in csv.DictReader(open(os.path.join(HERE, "e1_summary.csv")))
        if r["degenerate"] in ("", "False", "0") and r["speedup_vs_best"] not in ("", "nan")]
G = {}
for crit in ("NRS", "FRS"):
    v = sorted((float(r["speedup_vs_best"]), r["speedup_is_lower_bound"] in ("1", "True"), r["dataset"], r["param"])
               for r in rows if r["criterion"] == crit)
    G[crit] = v
    s = [x[0] for x in v]
    print(f"{crit}: n={len(s)} >=2x {sum(x >= 2 for x in s)} median {st.median(s):.1f} lower bounds "
          f"{sum(x[1] for x in v)} below 2x {[(x[2], x[3], round(x[0], 2)) for x in v if x[0] < 2]}")

mark = {"NRS": "*", "FRS": "triangle*"}
omark = {"NRS": "o", "FRS": "triangle"}
start = {"NRS": 1, "FRS": len(G["NRS"]) + 4}
plots, arrows, meds, labels = [], [], [], []
for crit, v in G.items():
    x0 = start[crit]
    ex = " ".join(f"({x0 + i},{s:.4g})" for i, (s, lb, _, _) in enumerate(v) if not lb)
    lb = " ".join(f"({x0 + i},{s:.4g})" for i, (s, lb, _, _) in enumerate(v) if lb)
    plots.append(f"\\addplot[only marks, mark={mark[crit]}, mark size=1.6pt, cBound] coordinates {{{ex}}};")
    plots.append(f"\\addplot[only marks, mark={omark[crit]}, mark size=1.6pt, cBound, mark options={{fill=white}}] "
                 f"coordinates {{{lb}}};")
    for i, (s, l, _, _) in enumerate(v):
        if l:
            arrows.append(f"\\draw[->, cBound, >=stealth] (axis cs:{x0 + i},{s * 1.18:.4g}) -- "
                          f"(axis cs:{x0 + i},{s * 1.75:.4g});")
    med = st.median([s for s, _, _, _ in v]); x1 = x0 + len(v) - 1
    meds.append(f"\\draw[black, thick] (axis cs:{x0 - 0.5},{med:.4g}) -- (axis cs:{x1 + 0.5},{med:.4g});")
    meds.append(f"\\node[anchor=south west, font=\\scriptsize, fill=white, inner sep=1pt] at (axis cs:{x0 - 0.3},{med * 1.08:.4g}) "
                f"{{median {med:.1f}}};")
    n = len(v); k = sum(s >= 2 for s, _, _, _ in v)
    labels.append(f"\\node[font=\\small, anchor=north] at (axis cs:{(x0 + x1) / 2},0.3) "
                  f"{{{crit}: ${k}$ of ${n}$ configurations $\\ge2\\times$}};")

xmax = start["FRS"] + len(G["FRS"])
body = f"""% generated by e1/make_fig_speed.py from e1/e1_summary.csv -- do not edit by hand
\\begin{{tikzpicture}}
\\begin{{axis}}[width=\\linewidth, height=6.2cm, ymode=log, xmin=0, xmax={xmax}, ymin=0.5, ymax=600,
  xtick=\\empty, ylabel={{speed-up}}, label style={{font=\\small}},
  tick label style={{font=\\scriptsize}}, clip=false,
  legend cell align=left, legend style={{font=\\scriptsize, at={{(0.01,0.98)}}, anchor=north west, draw=none, fill=white, fill opacity=0.85, text opacity=1}}]
\\addplot[gray, dashed, domain=0:{xmax}] {{1}};
\\addplot[gray, densely dotted, domain=0:{xmax}] {{2}};
{chr(10).join(plots)}
\\legend{{,,NRS, NRS lower bound, FRS, FRS lower bound}}
\\draw[gray!60] (axis cs:{start['FRS'] - 2},0.5) -- (axis cs:{start['FRS'] - 2},600);
\\node[font=\\scriptsize, gray, anchor=south east] at (axis cs:{xmax},1) {{$1\\times$}};
\\node[font=\\scriptsize, gray, anchor=south east] at (axis cs:{xmax},2) {{$2\\times$}};
{chr(10).join(arrows)}
{chr(10).join(meds)}
{chr(10).join(labels)}
\\end{{axis}}
\\end{{tikzpicture}}
"""
open(OUT, "w").write(body)
