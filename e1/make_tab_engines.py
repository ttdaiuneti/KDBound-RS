"""Generate paper/manuscript/tab_engines.tex (Table 6: every engine with and without the bound, NRS delta = 0.10) and
print the statistics of Section 5.5. Source: e1_raw.jsonl (superseded rows excluded; pair-engine +B3 rows are the
section-12 re-run)."""
import collections
import json
import os
import statistics as st

from scipy import stats

from run_e1 import superseded, is_superseded

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "paper", "manuscript", "tab_engines.tex")
sup = superseded(); T = collections.defaultdict(dict); ST = {}; MEM = collections.defaultdict(list)
for r in map(json.loads, open(os.path.join(HERE, "e1_raw.jsonl"))):
    if is_superseded(r, sup) or r["criterion"] != "NRS" or r["param"] != "0.10":
        continue
    k = (r["dataset"], r["method"])
    if r["fold"] == 1:
        ST[k] = r["status"]
    if r["status"] == "ok":
        T[k][r["fold"]] = r["time"]
    if r.get("peak_footprint_gb") is not None:
        MEM[k].append(r["peak_footprint_gb"])
DS = ["mammography", "htru2", "magic-telescope", "house-16h", "gas-drift", "internet-firewall", "jannis", "run-or-walk",
      "vehicle-sensit", "miniboone", "creditcard", "hls4ml-jets"]
EN = ["KD-PA", "FNC", "HASH", "CABIN", "BUCKET", "BF-PA"]
PAIR = ["HASH", "CABIN", "BUCKET", "BF-PA"]


def cell(ds, m):
    t = T[(ds, m)]
    if len(t) == 5:
        v = st.mean(t.values())
        return f"{v:.1f}" if v < 100 else f"{v:.0f}"
    return {"timeout": "T", "memout": "M"}.get(ST.get((ds, m)), "?")


lines = [f"{ds} & " + " & ".join(f"{cell(ds, e)} / {cell(ds, e + '+B3')}" for e in EN) + " \\\\" for ds in DS]
TEMPLATE = r"""\begin{table}[pos=htbp]
\centering
\caption{Each engine without / with the witness bound, NRS with $\delta=0.10$: mean reduction time over five folds
(seconds). T: exceeded $900$\,s on fold~1; M: memory limit on fold~1 (FNC: more than $3\cdot10^8$ pairs; other
engines: physical footprint above $32$\,GB).}
\label{tab:engines}
\small
\setlength{\tabcolsep}{3.5pt}
\begin{tabular}{@{}lrrrrrr@{}}
\toprule
Dataset & KD-PA & FNC & HASH & CABIN & BUCKET & BF-PA \\
\midrule
@@ROWS@@
\bottomrule
\end{tabular}
\end{table}"""
open(OUT, "w").write("% generated by e1/make_tab_engines.py -- do not edit by hand\n" +
                     TEMPLATE.replace("@@ROWS@@", "\n".join(lines)) + "\n")
both, onlyB, onlyE = [], [], []
for e in PAIR:
    for ds in DS:
        a, b = T[(ds, e)], T[(ds, e + "+B3")]
        if len(a) == 5 and len(b) == 5:
            both.append((ds, e, st.mean(a.values()) / st.mean(b.values())))
        elif len(b) == 5:
            onlyB.append((ds, e))
        elif len(a) == 5:
            onlyE.append((ds, e, ST.get((ds, e + "+B3"))))
r = [x[2] for x in both]
at = [st.mean(T[(d, e)].values()) for d, e, _ in both]; bt = [st.mean(T[(d, e + "+B3")].values()) for d, e, _ in both]
print(f"pair engines, both finished: n={len(both)} median speed-up {st.median(r):.2f} range {min(r):.2f}-{max(r):.2f}, "
      f"B3 slower in {sum(x < 1 for x in r)}; one-sided Wilcoxon on paired mean times p="
      f"{stats.wilcoxon(at, bt, alternative='greater').pvalue:.3f}")
print("  slower:", [(d, e, round(x, 2)) for d, e, x in both if x < 1])
print("only E+B3 finished:", onlyB)
print("only E finished:", onlyE)
# footprints (sampled every 2 s; recorded only for rows run under pre-reg section 10)
allmem = collections.defaultdict(list); killed = []
for r in map(json.loads, open(os.path.join(HERE, "e1_raw.jsonl"))):
    if is_superseded(r, sup) or r.get("peak_footprint_gb") is None:
        continue
    if r["status"] == "memout" and "footprint" in str(r.get("note", "")):
        killed.append(r["peak_footprint_gb"])
    elif r["status"] != "memout":
        allmem[r["method"]].append(r["peak_footprint_gb"])
print("stopped by the footprint cap: n=%d, sampled peak %.1f-%.1f GB" % (len(killed), min(killed), max(killed)))
print("largest footprint of runs not stopped (GB):", {m: round(max(v), 1) for m, v in sorted(allmem.items())})
# evaluation counts of the nearest-enemy-witness engines with the bound (all NRS parameters, per fold)
NEW = ["KD-PA+B3", "FNC+B3", "CABIN+B3", "BUCKET+B3", "BF-PA+B3"]; EVc = collections.defaultdict(dict)
for r in map(json.loads, open(os.path.join(HERE, "e1_raw.jsonl"))):
    if not is_superseded(r, sup) and r["status"] == "ok" and r["criterion"] == "NRS" and r["method"] in NEW:
        EVc[(r["dataset"], r["param"], r["fold"])][r["method"]] = r["evals"]
grp = [v for v in EVc.values() if len(v) >= 2]
print("folds with >=2 nearest-witness +B3 engines: %d, identical evaluation counts in %d; differing: %s" % (
    len(grp), sum(len(set(v.values())) == 1 for v in grp),
    [(k, v) for k, v in EVc.items() if len(v) >= 2 and len(set(v.values())) > 1]))
