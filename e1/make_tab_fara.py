"""Generate paper/manuscript/tab_fara.tex (Table 5: NRS, delta = 0.10: exact reduct vs FARA) and print the aggregate
statistics of Section 5.6. Sources: e1_summary.csv (|R|, accuracy), e1_raw.jsonl (FARA times)."""
import collections
import csv
import json
import os
import statistics as st

import numpy as np
from scipy import stats

from run_e1 import superseded, is_superseded

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "paper", "manuscript", "tab_fara.tex")
S = {(r["dataset"], r["criterion"], r["param"]): r for r in csv.DictReader(open(os.path.join(HERE, "e1_summary.csv")))}
sup = superseded(); T = collections.defaultdict(list)
for r in map(json.loads, open(os.path.join(HERE, "e1_raw.jsonl"))):
    if not is_superseded(r, sup) and r["status"] == "ok" and r["method"] == "FARA":
        T[(r["dataset"], r["criterion"], r["param"])].append(r["time"])
DS = ["mammography", "gas-drift", "htru2", "magic-telescope", "house-16h", "internet-firewall", "jannis", "run-or-walk",
      "vehicle-sensit", "miniboone", "creditcard", "hls4ml-jets"]
f = lambda x, p=1: "--" if x in ("", None) else f"{float(x):.{p}f}"
acc = lambda r, g, c: "--" if not r[f"{g}_{c}_mean"] else f"{100 * float(r[g + '_' + c + '_mean']):.1f} $\\pm$ {100 * float(r[g + '_' + c + '_std']):.1f}"
lines = []
for ds in DS:
    r = S[(ds, "NRS", "0.10")]; t = T.get((ds, "NRS", "0.10"), [])
    ft = f"{st.mean(t):.1f}" if len(t) == 5 else "$>900$"
    ot = f(r["ours_mean"]) if r["ours_folds"] == "5" else "$>900$"
    lines.append(f"{ds} & {ot} & {ft} & {f(r['exact_R_mean'])} & {f(r['fara_R_mean'])} & "
                 f"{acc(r, 'EXACT', 'svm')} & {acc(r, 'FARA', 'svm')} & {acc(r, 'EXACT', '3nn')} & {acc(r, 'FARA', '3nn')} \\\\")
TEMPLATE = r"""\begin{table}[pos=htbp]
\centering
\caption{Exact greedy reduct (any exact method) against FARA, NRS with $\delta=0.10$: reduction time of KD-PA+B3 and
of FARA (mean, seconds), reduct size and classification accuracy (\%, mean $\pm$ std over five folds) of the
SVM-RBF and 3-NN classifiers trained on the reduct. ``--'': not available (no exact method or FARA finished).}
\label{tab:fara}
\small
\setlength{\tabcolsep}{3.5pt}
\begin{tabular}{@{}lrrrrllll@{}}
\toprule
 & \multicolumn{2}{c}{time (s)} & \multicolumn{2}{c}{$|R|$} & \multicolumn{2}{c}{SVM-RBF} & \multicolumn{2}{c}{3-NN} \\
\cmidrule(lr){2-3}\cmidrule(lr){4-5}\cmidrule(lr){6-7}\cmidrule(l){8-9}
Dataset & ours & FARA & exact & FARA & exact & FARA & exact & FARA \\
\midrule
@@ROWS@@
\bottomrule
\end{tabular}
\end{table}"""
open(OUT, "w").write("% generated by e1/make_tab_fara.py -- do not edit by hand\n" + TEMPLATE.replace("@@ROWS@@", "\n".join(lines)) + "\n")
rows = [r for (ds, c, p), r in S.items() if c == "NRS" and r["EXACT_svm_mean"] and r["FARA_svm_mean"]]
for c in ("svm", "3nn"):
    e = np.array([float(r[f"EXACT_{c}_mean"]) for r in rows]); g = np.array([float(r[f"FARA_{c}_mean"]) for r in rows])
    d = g - e
    print(f"{c}: n={len(rows)} FARA higher {(d > 5e-4).sum()} lower {(d < -5e-4).sum()} equal {(abs(d) <= 5e-4).sum()} "
          f"Wilcoxon p={stats.wilcoxon(e, g).pvalue:.3f}; jannis gaps {[round(100 * x, 1) for x, r in zip(d, rows) if r['dataset'] == 'jannis']}")
fr = [(r["dataset"], r["param"], float(r["ours_mean"]), st.mean(T[k]))
      for k, r in S.items() if k[1] == "NRS" and r["ours_folds"] == "5" and len(T.get(k, [])) == 5 and r["degenerate"] == "0"]
faster = [x for x in fr if x[3] < x[2]]
print(f"FARA vs KD-PA+B3 time on {len(fr)} NRS configs: FARA faster in {len(faster)}: {[(a, b, round(c, 1), round(d, 1)) for a, b, c, d in faster]}")
print("median ratio FARA/ours %.2f" % st.median(d / c for _, _, c, d in fr))
