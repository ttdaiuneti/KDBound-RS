"""Generate paper/manuscript/tab_speed.tex (Table 4: NRS delta = 0.10 and FRS sigma = 0.25, one row per dataset)
from e1_summary.csv. No number is typed by hand."""
import csv
import os

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "paper", "manuscript", "tab_speed.tex")
rows = {(r["dataset"], r["criterion"], r["param"]): r for r in csv.DictReader(open(os.path.join(HERE, "e1_summary.csv")))}
DS = ["electrical-grid-stability", "mammography", "gas-drift", "htru2", "magic-telescope", "house-16h", "fried",
      "internet-firewall", "jannis", "run-or-walk", "vehicle-sensit", "miniboone", "creditcard", "hls4ml-jets"]


def f(x, p=1):
    return f"{float(x):.{p}f}"


def cells(r):
    if r is None:
        return ["\\multicolumn{3}{c}{not applied}"]
    if r["ours_folds"] != "5":
        return ["$>900$", "none$^{\\dagger}$", "--"]
    ours = f"{f(r['ours_mean'])} $\\pm$ {f(r['ours_std'])}"
    if r["best_existing"].startswith("none"):
        best, sp = "none$^{\\dagger}$", f"$>{f(r['speedup_vs_best'])}$"
    else:
        best, sp = f"{r['best_existing']} {f(r['best_mean'])}", f(r["speedup_vs_best"])
    if r["degenerate"] == "1":
        sp += "$^{d}$"
    return [ours, best, sp]


lines = []
for ds in DS:
    a = cells(rows.get((ds, "NRS", "0.10"))); b = cells(rows.get((ds, "FRS", "0.25")))
    lines.append(f"{ds} & " + " & ".join(a) + " & " + " & ".join(b) + " \\\\")
TEMPLATE = r"""\begin{table}[t]
\centering
\caption{Reduction time of KD-PA+B3 (mean $\pm$ std over five folds, seconds), fastest existing exact accelerator
that finished all folds (mean time) and speed-up, for NRS with $\delta=0.10$ and FRS with $\sigma=0.25$.
$^{\dagger}$No existing exact method finished all folds within $900$\,s or the memory limit; the speed-up is then the
lower bound $900/\text{mean}$. ``$>900$'': no method finished.}
\label{tab:speed}
\small
\begin{tabular}{@{}lrlrrlr@{}}
\toprule
 & \multicolumn{3}{c}{NRS, $\delta=0.10$} & \multicolumn{3}{c}{FRS, $\sigma=0.25$} \\
\cmidrule(lr){2-4}\cmidrule(l){5-7}
Dataset & KD-PA+B3 & best existing & speed-up & KD-PA+B3 & best existing & speed-up \\
\midrule
@@ROWS@@
\bottomrule
\end{tabular}
\end{table}"""
open(OUT, "w").write("% generated by e1/make_tab_speed.py from e1/e1_summary.csv -- do not edit by hand\n" +
                     TEMPLATE.replace("@@ROWS@@", "\n".join(lines)) + "\n")
print("\n".join(lines))
