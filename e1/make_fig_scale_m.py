"""Supplementary figure (e1_prereg.md section 14): gas-drift, fold 1, nested random attribute subsets.
(a) reduction time of KD-PA and KD-PA+B3 against m (geometric mean over the three subsets); (b) speed-up of the bound,
KD-PA / KD-PA+B3, per subset. A timeout of KD-PA is drawn at 900 s and its ratio as a lower bound.
Checks that both methods return the same ordered reduct. Output: ../paper/manuscript/fig_scale_m.tex (+ printed numbers).
"""
import json
import math
import os
import statistics as st

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "paper", "manuscript", "fig_scale_m.tex")
LIMIT = 900
rows = [json.loads(l) for l in open(os.path.join(HERE, "scale_m.jsonl"))]
D = {(r["m"], r["seed"], r["criterion"], r["method"]): r for r in rows}
MS = (16, 32, 64, 128)
seeds = lambda m: (0, 1, 2) if m < 128 else (-1,)  # noqa: E731
bad = [k for k, r in D.items() if k[3] == "KD-PA" and r["status"] == "ok"
       and D[(k[0], k[1], k[2], "KD-PA+B3")]["status"] == "ok" and D[(k[0], k[1], k[2], "KD-PA+B3")]["R"] != r["R"]]
assert not bad, bad

T, RAT, LB, FR = {}, {}, {}, {}
for c in ("NRS", "FRS"):
    for m in MS:
        for meth in ("KD-PA", "KD-PA+B3"):
            ts = [D[(m, s, c, meth)] for s in seeds(m)]
            T[(c, m, meth)] = (math.exp(st.mean(math.log(r["time"] if r["status"] == "ok" else LIMIT) for r in ts)),
                               any(r["status"] != "ok" for r in ts))
        rr, lb, fr = [], [], []
        for s in seeds(m):
            a, b = D[(m, s, c, "KD-PA")], D[(m, s, c, "KD-PA+B3")]
            if a["status"] == "ok":
                rr.append(a["time"] / b["time"]); fr.append(b["evals"] / a["evals"])
            else:
                lb.append(LIMIT / b["time"])
        RAT[(c, m)], LB[(c, m)], FR[(c, m)] = rr, lb, fr
        allr = rr + lb
        print(f"{c} m={m:3d}: speed-up geo {math.exp(st.mean(map(math.log, allr))):.2f} "
              f"range {min(allr):.2f}-{max(allr):.2f} (lower bounds {len(lb)}); evaluated fraction "
              f"{', '.join(f'{x:.2f}' for x in fr) or '-'}; times KD-PA {T[(c, m, 'KD-PA')][0]:.1f}"
              f"{'+' if T[(c, m, 'KD-PA')][1] else ''} KD-PA+B3 {T[(c, m, 'KD-PA+B3')][0]:.1f} s")

STY = {("NRS", "KD-PA+B3"): "cBound, thick, mark=*", ("NRS", "KD-PA"): "cEngine, thick, dashed, mark=o",
       ("FRS", "KD-PA+B3"): "cBound, thick, mark=triangle*", ("FRS", "KD-PA"): "cEngine, thick, dashed, mark=triangle"}
pa = []
for c in ("NRS", "FRS"):
    for meth in ("KD-PA+B3", "KD-PA"):
        pts = [(m, T[(c, m, meth)][0]) for m in MS if not T[(c, m, meth)][1]]
        pa.append(f"\\addplot[{STY[(c, meth)]}, mark size=1.6pt] coordinates {{{' '.join(f'({m},{t:.4g})' for m, t in pts)}}};")
        cens = [m for m in MS if T[(c, m, meth)][1]]
        if cens:
            prev = pts[-1]
            pa.append(f"\\addplot[{STY[(c, meth)].replace('thick, dashed', 'thick, densely dotted')}, mark size=1.6pt, "
                      f"forget plot, mark options={{fill=white}}] coordinates {{({prev[0]},{prev[1]:.4g}) ({cens[0]},{LIMIT})}};")
            pa.append(f"\\draw[->, cEngine, >=stealth] (axis cs:{cens[0]},{LIMIT * 1.15:.4g}) -- (axis cs:{cens[0]},{LIMIT * 1.9:.4g});")
pb = []
for c, mk in (("NRS", "*"), ("FRS", "triangle*")):
    sh = 0.94 if c == "NRS" else 1.06
    ex = " ".join(f"({m * sh:.4g},{v:.4g})" for m in MS for v in RAT[(c, m)])
    pb.append(f"\\addplot[only marks, mark={mk}, mark size=1.6pt, cBound] coordinates {{{ex}}};")
    geo = " ".join(f"({m * sh:.4g},{math.exp(st.mean(map(math.log, RAT[(c, m)] + LB[(c, m)]))):.4g})" for m in MS)
    pb.append(f"\\addplot[cBound, thin, forget plot] coordinates {{{geo}}};")
    for m in MS:
        for v in LB[(c, m)]:
            pb.append(f"\\addplot[only marks, mark={mk.rstrip('*')}, mark size=1.6pt, cBound, forget plot, "
                      f"mark options={{fill=white}}] coordinates {{({m * sh:.4g},{v:.4g})}};")
            pb.append(f"\\draw[->, cBound, >=stealth] (axis cs:{m * sh:.4g},{v * 1.12:.4g}) -- (axis cs:{m * sh:.4g},{v * 1.55:.4g});")

ax = ("xmode=log, log basis x=2, xtick={16,32,64,128}, xticklabels={16,32,64,128}, xmin=12, xmax=170, "
      "xlabel={number of attributes $m$}, tick label style={font=\\scriptsize}, label style={font=\\scriptsize}, "
      "title style={font=\\small}, legend cell align=left")
body = f"""% generated by e1/make_fig_scale_m.py from e1/scale_m.jsonl -- do not edit by hand
\\begin{{tikzpicture}}
\\begin{{axis}}[at={{(0,0)}}, anchor=south west, width=0.5\\linewidth, height=5.2cm, ymode=log, ymin=1, ymax=3000,
  ylabel={{time (s)}}, title={{(a) reduction time}}, {ax},
  legend style={{font=\\scriptsize, at={{(0.02,0.98)}}, anchor=north west, draw=none, fill=white, fill opacity=0.85, text opacity=1}}]
\\addplot[gray, dashed, domain=12:170, forget plot] {{{LIMIT}}};
{chr(10).join(pa)}
\\legend{{NRS KD-PA+B3, NRS KD-PA, FRS KD-PA+B3, FRS KD-PA}}
\\end{{axis}}
\\begin{{axis}}[at={{(0.53\\linewidth,0)}}, anchor=south west, width=0.5\\linewidth, height=5.2cm, ymode=log, ymin=0.7, ymax=20,
  ytick={{1,2,5,10}}, yticklabels={{1,2,5,10}}, ylabel={{speed-up of the bound}}, title={{(b) KD-PA time / KD-PA+B3 time}}, {ax},
  legend style={{font=\\scriptsize, at={{(0.02,0.98)}}, anchor=north west, draw=none, fill=white, fill opacity=0.85, text opacity=1}}]
\\addplot[gray, dashed, domain=12:170, forget plot] {{1}};
{chr(10).join(pb)}
\\legend{{NRS, FRS}}
\\end{{axis}}
\\end{{tikzpicture}}
"""
open(OUT, "w").write(body)
