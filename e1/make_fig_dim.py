"""Generate paper/manuscript/fig_dim.tex (pgfplots, two panels) and print the statistics quoted in Section 5.4.
Source: e1_summary.csv (speed-ups) and e1_raw.jsonl (evaluation counts); usable configurations only
(KD-PA+B3 finished all folds, not degenerate)."""
import collections
import csv
import json
import os
import statistics as st

from scipy import stats

from run_e1 import superseded, is_superseded
from data_e1 import load

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "paper", "manuscript", "fig_dim.tex")
sup = superseded(); ev = collections.defaultdict(lambda: collections.defaultdict(list))
for r in map(json.loads, open(os.path.join(HERE, "e1_raw.jsonl"))):
    if not is_superseded(r, sup) and r["status"] == "ok" and r["method"] in ("KD-PA", "KD-PA+B3"):
        ev[(r["dataset"], r["criterion"], r["param"])][r["method"]].append(r["evals"])
rows = [r for r in csv.DictReader(open(os.path.join(HERE, "e1_summary.csv")))
        if r["ours_folds"] == "5" and r["degenerate"] == "0"]
M = {s: load(s)[0].shape[1] for s in {r["dataset"] for r in rows}}
pts = {"bound": collections.defaultdict(list), "engine": collections.defaultdict(list),
       "frac": collections.defaultdict(list)}
Bm, Bs, Bf = [], [], []
for r in rows:
    k = (r["dataset"], r["criterion"], r["param"]); m = M[r["dataset"]]
    if r["speedup_vs_kdpa"]:
        b = float(r["speedup_vs_kdpa"]); fr = st.mean(ev[k]["KD-PA+B3"]) / st.mean(ev[k]["KD-PA"])
        pts["bound"][r["criterion"]].append((m, b)); pts["frac"][r["criterion"]].append((m, fr))
        Bm.append(m); Bs.append(b); Bf.append(fr)
        if r["best_mean"] and r["kdpa_mean"]:
            pts["engine"][r["criterion"]].append((m, float(r["best_mean"]) / float(r["kdpa_mean"])))
small = [b for b, m in zip(Bs, Bm) if m <= 16]; large = [b for b, m in zip(Bs, Bm) if m >= 29]
eng = [y for c in pts["engine"].values() for _, y in c]
print(f"configurations with KD-PA complete: {len(Bs)}")
print(f"bound speed-up, m<=16: n={len(small)} median {st.median(small):.2f} range {min(small):.2f}-{max(small):.2f}; "
      f"slower (<1) in {sum(b < 1 for b in small)}")
print(f"bound speed-up, m>=29: n={len(large)} median {st.median(large):.2f} range {min(large):.2f}-{max(large):.2f}")
print("spearman(m, bound speed-up) rho=%.2f p=%.1e" % stats.spearmanr(Bm, Bs))
print("spearman(m, evaluated fraction) rho=%.2f p=%.1e" % stats.spearmanr(Bm, Bf))
print("spearman(evaluated fraction, bound speed-up) rho=%.2f p=%.1e" % stats.spearmanr(Bf, Bs))
print(f"engine part (best existing / KD-PA): n={len(eng)} median {st.median(eng):.1f} range {min(eng):.1f}-{max(eng):.1f}")
print(f"evaluated fraction range {min(Bf):.2f}-{max(Bf):.2f}")

style = {"NRS": "mark=*", "FRS": "mark=triangle*"}


def plot(series, opts):
    out = []
    for crit in ("NRS", "FRS"):
        p = series.get(crit, [])
        if not p:
            continue
        c = " ".join(f"({m},{y:.4g})" for m, y in sorted(p))
        out.append(f"\\addplot[only marks,{style[crit]},{opts}] coordinates {{{c}}};")
    return "\n".join(out)


body = f"""% generated by e1/make_fig_dim.py from e1/e1_summary.csv and e1/e1_raw.jsonl -- do not edit by hand
\\begin{{tikzpicture}}
\\begin{{axis}}[name=a, width=0.5\\linewidth, height=5.6cm, xmode=log, ymode=log, log basis x=2,
  xtick={{6,8,16,32,64,128}}, xticklabels={{6,8,16,32,64,128}}, xlabel={{number of attributes $m$}},
  ylabel={{speed-up}}, title={{(a) speed-up by component}}, legend style={{font=\\scriptsize, at={{(0.5,-0.32)}}, anchor=north, legend columns=4, draw=none}},
  tick label style={{font=\\scriptsize}}, label style={{font=\\small}}, title style={{font=\\small}}]
\\addplot[gray, dashed, domain=5:140] {{1}};
{plot(pts["engine"], "draw=cEngine, mark options={fill=white, draw=cEngine, line width=0.8pt, scale=1.0}")}
{plot(pts["bound"], "draw=cBound, mark options={fill=cBound, draw=cBound, scale=0.8}")}
\\legend{{,engine NRS,engine FRS,bound NRS,bound FRS}}
\\end{{axis}}
\\begin{{axis}}[at={{(a.east)}}, anchor=west, xshift=1.4cm, width=0.5\\linewidth, height=5.6cm, xmode=log, log basis x=2,
  xtick={{6,8,16,32,64,128}}, xticklabels={{6,8,16,32,64,128}}, xlabel={{number of attributes $m$}}, ymin=0, ymax=1.05,
  ylabel={{evaluations with / without bound}}, title={{(b) candidates evaluated}},
  tick label style={{font=\\scriptsize}}, label style={{font=\\small}}, title style={{font=\\small}}]
{plot(pts["frac"], "draw=cBound, mark options={fill=cBound, draw=cBound, scale=0.8}")}
\\end{{axis}}
\\end{{tikzpicture}}
"""
open(OUT, "w").write(body)
